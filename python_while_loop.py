# Python while Loop 

# A while loop repeatedly executes code as long as a condition is True.

# Syntax :

# while condition:
#     statement


# Example :

count = 1

while count <= 5:
    print(count)
    count += 1


# How it works
# count = 1
#     ↓
# count <= 5 ?
#     ↓
#    YES
#     ↓
# print(count)
#     ↓
# count += 1
#     ↓
# # Check condition again