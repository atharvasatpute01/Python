# Python OOP – Encapsulation
# Encapsulation is one of the four major pillars of Object-Oriented Programming (OOP).

# 1. What is Encapsulation?
# Encapsulation is the process of wrapping data (variables) and methods (functions) together inside a class and controlling access to that data.

# In simple words: Encapsulation protects data from unwanted or invalid modifications.

# Real-world example: ATM Machine
# - You can check your bank balance.
# - You can deposit money.
# - You can withdraw money.
# - You cannot directly modify the bank's internal balance.





# 2. Access Modifiers in Python
# Python uses three naming conventions for access control.

# Type              Syntax              Description

# Public            name                Accessible from anywhere
# Protected         _name               Intended for internal use and subclasses
# Private           __name              Uses name mangling to discourage direct access