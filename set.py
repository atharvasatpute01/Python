# Python Sets

# A Set in Python is a collection that:

# is unordered
# contains unique values
# is mutable
# does not allow duplicate elements
# supports mathematical set operations such as union, intersection, difference


# Basic Syntax :
my_set = {10, 20, 30, 40}

print(my_set)
print(type(my_set))

# Important : {} creates an empty dictionary, not an empty set.