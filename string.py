# Python Strings

# What is a String?

# A String is a sequence of characters enclosed within:

# Single quotes ' '
# Double quotes " "
# Triple quotes ''' ''' or """ """

# A String is represented by the str data type




# Creating Strings

# Using Single Quotes

name = 'Atharva'

print(name)
print(type(name))

# Using Double Quotes

city = "Pune"

print(city)

# Using Triple Quotes (Multi-line String)

address = """Flat No 101
Pune
Maharashtra
India"""

print(address)